const SURF = { A: "Paved", U: "Unpaved", X: "Unknown" };

const AIRPORTS = D.map(([icao, name, mu, cc, elev, rwys]) => ({
  icao, name, municipality: mu || "", country: cc, elev,
  runways: rwys.map(([le, he, len, slope, code]) => ({
    ends: le + "/" + he, le, he, len, slope, surface: SURF[code] || "Unknown",
  })),
}));

const BY_ICAO = new Map(AIRPORTS.map((a) => [a.icao, a]));

/* Every selectable runway end. Slope is signed for the direction of take-off:
   positive is uphill, so the reciprocal of an uphill end is a downhill end. */
function endsOf(airport) {
  const out = [];
  airport.runways.forEach((r) => {
    out.push({ end: r.le, ends: r.ends, len: r.len, slope: r.slope, surface: r.surface });
    out.push({ end: r.he, ends: r.ends, len: r.len, slope: -r.slope, surface: r.surface });
  });
  return out.sort((a, b) => parseInt(a.end, 10) - parseInt(b.end, 10) || (a.end < b.end ? -1 : 1));
}

function headingOf(end) { return parseInt(end, 10) * 10; }

function findAirport(icao) {
  return BY_ICAO.get(String(icao || "").trim().toUpperCase()) || null;
}

/* Type-ahead over ICAO, name and municipality. */
function searchAirports(q, limit = 8) {
  const s = String(q || "").trim().toUpperCase();
  if (s.length < 2) return [];
  const starts = [], has = [];
  for (const a of AIRPORTS) {
    if (a.icao.startsWith(s)) { starts.push(a); if (starts.length >= limit) break; continue; }
    if (has.length < limit && (a.name.toUpperCase().includes(s) || a.municipality.toUpperCase().includes(s))) has.push(a);
  }
  return starts.concat(has).slice(0, limit);
}

window.PG_AIRPORTS = { AIRPORTS, endsOf, headingOf, findAirport, searchAirports };
